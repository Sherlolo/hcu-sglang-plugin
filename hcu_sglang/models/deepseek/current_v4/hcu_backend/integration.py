    # Import the complete owned graph before applying class replacements.
    owned={module:import_module(module) for _,module,_ in _FORMAL+_COMPATIBILITY}
    for original,module,name in _COMPATIBILITY:
        target=import_module(original)
        if not hasattr(target,name):
            setattr(target,name,getattr(owned[module],name))
    for target,module,name in _FORMAL:
        HookRegistry.register(target,getattr(owned[module],name),HookType.REPLACE)
    from . import forward_batch
    HookRegistry.register('sglang.srt.model_executor.forward_batch_info.ForwardBatch',
        forward_batch.ForwardBatch,HookType.REPLACE)
    from . import arg_groups
    HookRegistry.register('sglang.srt.arg_groups.deepseek_v4_hook.validate_deepseek_v4_cp',
        arg_groups.validate_deepseek_v4_cp,HookType.REPLACE)
    from . import collectives,overlap
